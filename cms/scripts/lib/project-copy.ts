/** 递归替换区块中的文本值，只替换明确列出的旧文案，不触碰图片、链接和 ID。 */
export function applyProjectCopy<T>(value: T, replacements: Record<string, string>): T {
  if (typeof value === 'string') return (replacements[value] ?? value) as T
  if (Array.isArray(value)) return value.map((item) => applyProjectCopy(item, replacements)) as T
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {}
    for (const [key, item] of Object.entries(value as Record<string, unknown>)) {
      out[key] = applyProjectCopy(item, replacements)
    }
    return out as T
  }
  return value
}
